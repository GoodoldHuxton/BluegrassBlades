local function log(s)
    print("[BluegrassBlades] " .. s)
end

--- Weight of vanilla knives already on a ProceduralDistributions item list ({name, weight, ...})
function BB.vanillaKnifeWeight(items)
    local total = 0
    for i = 1, #items - 1, 2 do
        local name = items[i]
        if type(name) == "string" then
            name = name:gsub("^Base%.", "")
            if BB.VANILLA_KNIVES[name] and type(items[i + 1]) == "number" then
                total = total + items[i + 1]
            end
        end
    end
    return total
end

function BB.insertLoot()
    local pd = ProceduralDistributions and ProceduralDistributions.list
    if not pd then
        log("ProceduralDistributions.list missing, no loot added")
        return
    end
    local byList, order = {}, {}
    for _, e in ipairs(BB.LOOT) do
        if not byList[e[1]] then
            byList[e[1]] = {}
            table.insert(order, e[1])
        end
        table.insert(byList[e[1]], e)
    end
    local added, lists, skipped, scaled = 0, 0, 0, 0
    BB.added = {}
    for _, listName in ipairs(order) do
        local list = pd[listName]
        if list and list.items then
            local ours = 0
            for _, e in ipairs(byList[listName]) do ours = ours + e[3] end
            local cap = BB.vanillaKnifeWeight(list.items) * BB.MAX_SHARE
            local k = 1
            if cap > 0 and ours > cap then
                k = cap / ours
                scaled = scaled + 1
                log(string.format("%s: our weight %.3f > %.3f (half of vanilla knives), scaled x%.3f", listName, ours, cap, k))
            end
            for _, e in ipairs(byList[listName]) do
                -- name and weight go in together, or the flat list shifts
                table.insert(list.items, e[2])
                table.insert(list.items, e[3] * k)
                added = added + 1
            end
            BB.added[listName] = { count = #byList[listName], weight = ours * k, scale = k }
            lists = lists + 1
        else
            skipped = skipped + 1
            log("no loot list '" .. listName .. "' in this build, skipped")
        end
    end
    log(string.format("loot: %d entries added to %d lists, %d lists skipped, %d lists scaled", added, lists, skipped, scaled))
end

Events.OnPreDistributionMerge.Add(BB.insertLoot)
